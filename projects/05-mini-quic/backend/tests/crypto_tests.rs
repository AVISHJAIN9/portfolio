// FEAT: 05-015
// ACCEPT: RFC 7748 X25519 Diffie-Hellman key agreement produces expected 32-byte shared secret
#[test]
fn test_x25519_key_agreement_rfc7748() {
    let alice_private = [
        0x77, 0x07, 0x6d, 0x0a, 0x73, 0x18, 0xa5, 0x7d, 0x3c, 0x16, 0xc1, 0x72, 0x51, 0xb2, 0x66, 0x45,
        0xdf, 0x4c, 0x2f, 0x87, 0xeb, 0xc0, 0x99, 0x2a, 0xb1, 0x77, 0xfb, 0xa5, 0x1d, 0xb9, 0x2c, 0x2a,
    ];
    let bob_public = [
        0xde, 0x9e, 0xdb, 0x7d, 0x7b, 0x7d, 0xc1, 0xb4, 0xd3, 0x5b, 0x61, 0xc2, 0xec, 0xe4, 0x35, 0x37,
        0x3f, 0x83, 0x43, 0xc8, 0x5b, 0x78, 0x67, 0x4d, 0xad, 0xfc, 0x7e, 0x14, 0x6f, 0x88, 0x2b, 0x4f,
    ];

    let shared_secret = x25519(&alice_private, &bob_public);
    let expected = [
        0x4a, 0x5d, 0x9d, 0x5b, 0xa4, 0xce, 0x2d, 0xe1, 0x72, 0x8e, 0x3b, 0xf4, 0x80, 0x35, 0x0f, 0x25,
        0xe0, 0x7e, 0x21, 0xc9, 0x47, 0xd1, 0x9e, 0x33, 0x76, 0xf0, 0x9b, 0x3c, 0x1e, 0x16, 0x17, 0x42,
    ];
    assert_eq!(shared_secret, expected);
}

// FEAT: 05-016
// ACCEPT: ChaCha20-Poly1305 packet protection validated against RFC 9001 Appendix A.5 vectors
#[test]
fn test_chacha20_poly1305_packet_protection() {
    // RFC 9001 Appendix A.5 ChaCha20-Poly1305 Short Header Packet test vector
    let secret = [
        0x9a, 0xc3, 0x12, 0xa7, 0xf8, 0x77, 0x46, 0x8e, 0xbe, 0x69, 0x42, 0x27, 0x48, 0xad, 0x00, 0xa1,
        0x54, 0x43, 0xf1, 0x82, 0x03, 0xa0, 0x7d, 0x60, 0x60, 0xf6, 0x88, 0xf3, 0x0f, 0x21, 0x63, 0x2b,
    ];
    let mut key = [0u8; 32];
    hkdf_expand_label(&secret, "quic key", b"", &mut key);
    let expected_key = [
        0xc6, 0xd9, 0x8f, 0xf3, 0x44, 0x1c, 0x3f, 0xe1, 0xb2, 0x18, 0x20, 0x94, 0xf6, 0x9c, 0xaa, 0x2e,
        0xd4, 0xb7, 0x16, 0xb6, 0x54, 0x88, 0x96, 0x0a, 0x7a, 0x98, 0x49, 0x79, 0xfb, 0x23, 0xe1, 0xc8,
    ];
    assert_eq!(key, expected_key);

    let mut iv = [0u8; 12];
    hkdf_expand_label(&secret, "quic iv", b"", &mut iv);
    let expected_iv = [
        0xe0, 0x45, 0x9b, 0x34, 0x74, 0xbd, 0xd0, 0xe4, 0x4a, 0x41, 0xc1, 0x44,
    ];
    assert_eq!(iv, expected_iv);

    let mut hp_key = [0u8; 32];
    hkdf_expand_label(&secret, "quic hp", b"", &mut hp_key);
    let expected_hp_key = [
        0x25, 0xa2, 0x82, 0xb9, 0xe8, 0x2f, 0x06, 0xf2, 0x1f, 0x48, 0x89, 0x17, 0xa4, 0xfc, 0x8f, 0x1b,
        0x73, 0x57, 0x36, 0x85, 0x60, 0x85, 0x97, 0xd0, 0xef, 0xcb, 0x07, 0x6b, 0x0a, 0xb7, 0xa7, 0xa4,
    ];
    assert_eq!(hp_key[..16], expected_hp_key[..16]);

    let pn = 654360564u64; // 0x270313f4
    let nonce = quic_aead_nonce(&iv, pn);
    let plaintext = [0x01]; // PING frame
    let aad = [0x42, 0x00, 0x27, 0x03, 0x13, 0xf4]; // Short header AAD

    let ciphertext = quic_chacha20_poly1305_encrypt(&key, &nonce, &plaintext, &aad).unwrap();
    assert_eq!(ciphertext.len(), plaintext.len() + 16);

    let decrypted = quic_chacha20_poly1305_decrypt(&key, &nonce, &ciphertext, &aad).unwrap();
    assert_eq!(decrypted, plaintext);
}

// FEAT: 05-017
// ACCEPT: Initial secrets, keys, IV, HP derivation and RFC 9001 Section 6 key update phase transitions
#[test]
fn test_rfc9001_initial_key_derivation() {
    let dcid = [0x83, 0x94, 0xc8, 0xf0, 0x3e, 0x51, 0x57, 0x08];
    let initial_salt = [
        0x38, 0x76, 0x2c, 0xf7, 0xf5, 0x59, 0x34, 0xb3, 0x4d, 0x17, 0x9a, 0xe6, 0xa4, 0xc8,
        0x0c, 0xad, 0xcc, 0xbb, 0x7f, 0x0a,
    ];
    let initial_secret = hkdf_extract(&initial_salt, &dcid);
    let mut client_initial_secret = [0u8; 32];
    hkdf_expand_label(&initial_secret, "client in", b"", &mut client_initial_secret);
    let expected_client_secret = [
        0xc0, 0x0c, 0xf1, 0x51, 0xca, 0x5b, 0xe0, 0x75, 0xed, 0x0e, 0xbf, 0xb5, 0xc8, 0x03,
        0x23, 0xc4, 0x2d, 0x6b, 0x7d, 0xb6, 0x78, 0x81, 0x28, 0x9a, 0xf4, 0x00, 0x8f, 0x1f,
        0x6c, 0x35, 0x7a, 0xea,
    ];
    assert_eq!(client_initial_secret, expected_client_secret);

    let mut client_key = [0u8; 16];
    hkdf_expand_label(&client_initial_secret, "quic key", b"", &mut client_key);
    assert_eq!(
        client_key,
        [0x1f, 0x36, 0x96, 0x13, 0xdd, 0x76, 0xd5, 0x46, 0x77, 0x30, 0xef, 0xcb, 0xe3, 0xb1, 0xa2, 0x2d]
    );

    let mut client_iv = [0u8; 12];
    hkdf_expand_label(&client_initial_secret, "quic iv", b"", &mut client_iv);
    assert_eq!(
        client_iv,
        [0xfa, 0x04, 0x4b, 0x2f, 0x42, 0xa3, 0xfd, 0x3b, 0x46, 0xfb, 0x25, 0x5c]
    );

    let mut client_hp = [0u8; 16];
    hkdf_expand_label(&client_initial_secret, "quic hp", b"", &mut client_hp);
    assert_eq!(
        client_hp,
        [0x9f, 0x50, 0x44, 0x9e, 0x04, 0xa0, 0xe8, 0x10, 0x28, 0x3a, 0x1e, 0x99, 0x33, 0xad, 0xed, 0xd2]
    );

    // RFC 9001 Section 6 Key Update
    let next_app_secret = quic_key_update(&client_initial_secret);
    assert_ne!(next_app_secret, client_initial_secret);
    let mut next_key = [0u8; 16];
    hkdf_expand_label(&next_app_secret, "quic key", b"", &mut next_key);
    assert_ne!(next_key, client_key);
}
